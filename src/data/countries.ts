/** Fallback for any country not in `PHONE_LENGTH_BY_ISO2` above. */
export const DEFAULT_PHONE_LENGTH: [number, number] = [6, 12];

export function phoneLengthFor(iso2: string): [number, number] {
  return PHONE_LENGTH_BY_ISO2[iso2] ?? DEFAULT_PHONE_LENGTH;
}

