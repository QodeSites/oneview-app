/**
 * ITU calling codes + ISO 3166-1 alpha-2, for the worldwide country-code
 * picker on the sign-in phone field (Qode's customers are not India-only).
 * Public, factual reference data — the same numbers on every phone's own
 * dialer settings.
 *
 * The ISO code also drives the flag icon (CountryCodePicker.tsx, via a
 * flag image CDN) — Unicode flag emoji were tried first but Android's
 * system font frequently has no combined glyph for a given
 * regional-indicator pair, so it fell back to showing the two bare
 * letters instead of a flag.
 */
export interface Country {
  name: string;
  iso2: string;
  dialCode: string;
}

